"""Swapped-option re-run of the readable-cue deference design (docs/DEFERENCE_SWAP_AMENDMENT.md, 2026-11-22).

    python scripts/116_deference_swap.py --stage design     # builds data/processed/deference_swap_design.csv (no calls)
    DEFERENCE_VARIANT=swap_model2 python scripts/24_deference.py --stage run    # then parse; same for swap_model3, swap_r1
    python scripts/116_deference_swap.py --stage readout    # results/deference/swap/REPORT.md
"""
import argparse, pathlib, re, sys
import numpy as np, pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]; SEED = 20261006
SRC = ROOT / "data/processed/deference_model2_design.csv"; DESIGN = ROOT / "data/processed/deference_swap_design.csv"
ORIG = {"swap_model2": ("Qwen3-32B", ROOT / "results/deference/model2/runs.csv"), "swap_model3": ("gpt-oss-120b", ROOT / "results/deference/model3/runs.csv"),
        "swap_r1": ("R1-0528", ROOT / "results/deference/replication/runs.csv")}
OPT = re.compile(r"^A\) (.*)\nB\) (.*)$", re.S)


def swap_prompt(p):
    head, _, tail = p.rpartition("\nA) ")
    m = OPT.match("A) " + tail); assert m and "\n" not in m.group(1), p[-200:]
    a, b = m.group(1), m.group(2)
    out = f"{head}\nA) {b}\nB) {a}"
    if "<answer>" in out:
        letter = re.search(r"<answer>([AB])</answer>", out).group(1); out = out.replace(f"<answer>{letter}</answer>", f"<answer>{'B' if letter == 'A' else 'A'}</answer>")
    return out


def design():
    d = pd.read_csv(SRC).copy()
    d["prompt"] = d.prompt.map(swap_prompt); flip = {"A": "B", "B": "A"}
    d["hint_letter"] = d.hint_letter.map(flip); d["target"] = d.target.map(flip); d["correct_is_A"] = ~d.correct_is_A.astype(bool)
    for x in d.itertuples():
        if x.cell != "control": assert f"<answer>{x.hint_letter}</answer>" in x.prompt and x.hint_letter != x.target
    d.to_csv(DESIGN, index=False); print(f"{len(d)} rows; hint_letter {d.drop_duplicates('qid').hint_letter.value_counts().to_dict()}")
    print(d[d.cell == "p95"].prompt.iloc[0]); print("--- original:"); print(pd.read_csv(SRC).query("cell=='p95'").prompt.iloc[0])


def effects(r):
    r = r[r.outcome == "answered"].copy(); r["key"] = (r.cell != "control").astype(int); r["followed"] = r.followed.astype(float)
    q = r.groupby(["qid", "hint_letter", "key"]).followed.mean().unstack("key").reset_index(); q["e"] = q[1] - q[0]
    q["ctrl_err"] = q.qid.map(r[r.key == 0].groupby("qid").followed.mean()); return r, q


def boot_diff(eA, eB, rng, n=2000):
    bs = [eB[rng.integers(0, len(eB), len(eB))].mean() - eA[rng.integers(0, len(eA), len(eA))].mean() for _ in range(n)]
    return float(eB.mean() - eA.mean()), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def readout():
    rng = np.random.default_rng(SEED); L = ["# Swapped-option re-run: readouts", "", "Amendment docs/DEFERENCE_SWAP_AMENDMENT.md (2026-11-22). Generated by scripts/116_deference_swap.py.", ""]
    rows, cb = [], []
    for v, (label, orig_path) in ORIG.items():
        p = ROOT / "results/deference/swap" / v / "runs.csv"
        if not p.exists(): L.append(f"- {label}: no swapped run on disk"); continue
        rs, qs = effects(pd.read_csv(p)); ro, qo = effects(pd.read_csv(orig_path))
        prov = rs.provider.value_counts().to_dict(); nonans = 1 - (pd.read_csv(p).outcome == "answered").mean()
        eA, eB = qs[qs.hint_letter == "A"].e.dropna().to_numpy(), qs[qs.hint_letter == "B"].e.dropna().to_numpy(); d, lo, hi = boot_diff(eA, eB, rng)
        verdict = "position bias" if lo > 0 else ("question set" if hi < 0 else "both or neither")
        s = qs[qs.ctrl_err == 0]; a2, b2 = s[s.hint_letter == "A"].e.dropna().to_numpy(), s[s.hint_letter == "B"].e.dropna().to_numpy(); d2, lo2, hi2 = boot_diff(a2, b2, rng)
        oA, oB = qo[qo.hint_letter == "A"].e.dropna().to_numpy(), qo[qo.hint_letter == "B"].e.dropna().to_numpy(); do, loo, hio = boot_diff(oA, oB, rng)
        # replication check and counterbalanced estimates
        fs, fo = rs.groupby("cell").followed.mean(), ro.groupby("cell").followed.mean()
        flags = [c for c in ("control", "p55", "p95") if c in fs and c in fo and abs(fs[c] - fo[c]) > (0.10 if c == "control" else 0.15)]
        m = qs[["qid", "hint_letter", "e"]].merge(qo[["qid", "hint_letter", "e"]], on="qid", suffixes=("_swap", "_orig"))
        m["e_cb"] = (m.e_swap + m.e_orig) / 2
        m["e_Bkey"] = np.where(m.hint_letter_swap == "B", m.e_swap, m.e_orig); m["e_Akey"] = np.where(m.hint_letter_swap == "A", m.e_swap, m.e_orig)
        pos = m.e_Bkey - m.e_Akey; bs = [pos.to_numpy()[rng.integers(0, len(pos), len(pos))].mean() for _ in range(2000)]
        rows.append(dict(model=label, n=len(rs), providers=prov, non_answered=round(nonans, 3), swap_effect_A=eA.mean(), swap_effect_B=eB.mean(), swap_B_minus_A=d, lo=lo, hi=hi, verdict=verdict,
                         always_right_B_minus_A=d2, ar_lo=lo2, ar_hi=hi2, orig_B_minus_A=do, orig_lo=loo, orig_hi=hio,
                         follow_swap=fs.round(3).to_dict(), follow_orig=fo.round(3).to_dict(), deployment_flags=flags,
                         counterbalanced_key_effect=float(m.e_cb.mean()), position_effect=float(pos.mean()), pos_lo=float(np.percentile(bs, 2.5)), pos_hi=float(np.percentile(bs, 97.5))))
        cb.append(m.assign(model=label))
    R = pd.DataFrame(rows); out = ROOT / "results/deference/swap"; out.mkdir(exist_ok=True)
    R.to_csv(out / "readouts.csv", index=False)
    if cb: pd.concat(cb).to_csv(out / "per_question_counterbalanced.csv", index=False)
    for x in R.itertuples():
        L += [f"## {x.model}", "", f"{x.n} answered runs; providers {x.providers}; non-answered share {x.non_answered}; deployment flags {x.deployment_flags or 'none'}.", "",
              f"Swapped run, key effect by the letter the key names: A {x.swap_effect_A:+.3f}, B {x.swap_effect_B:+.3f}; B − A = {x.swap_B_minus_A:+.3f} [{x.lo:+.3f}, {x.hi:+.3f}] → **{x.verdict}**. "
              f"(Original run: B − A = {x.orig_B_minus_A:+.3f} [{x.orig_lo:+.3f}, {x.orig_hi:+.3f}].) Among questions always right in control: {x.always_right_B_minus_A:+.3f} [{x.ar_lo:+.3f}, {x.ar_hi:+.3f}].", "",
              f"Follow rates by cell, swapped {x.follow_swap} against original {x.follow_orig}. Counterbalanced per-question key effect {x.counterbalanced_key_effect:+.3f}; "
              f"position effect (B-key minus A-key within question, both orders) {x.position_effect:+.3f} [{x.pos_lo:+.3f}, {x.pos_hi:+.3f}].", ""]
    open(out / "REPORT.md", "w").write("\n".join(L)); print("\n".join(L))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--stage", required=True, choices=["design", "readout"]); a = ap.parse_args()
    design() if a.stage == "design" else readout()
